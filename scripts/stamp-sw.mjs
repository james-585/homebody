// Stamps the service worker with a content hash of the app shell (ADR 0003).
//   node scripts/stamp-sw.mjs [--check] [rootDir]
// Hashes every shell file (index.html, manifest.json, icon-*.png, every file under src/ and fonts/) and
// sw.js itself with the generated block removed, then rewrites the marked block in sw.js.
// --check writes nothing and exits 1 if the block is stale or the markers are wrong.
import { createHash } from 'node:crypto';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const BEGIN = '// >>> stamp-sw:begin';
const END = '// <<< stamp-sw:end';
const BEGIN_NOTE = ' (generated by scripts/stamp-sw.mjs; run `npm run stamp`, do not edit)';

/** Shell files of these types are cached at install; the rest (licences, notes) are only hashed. */
const RUNTIME_FILE = /\.(html|json|png|js|woff2)$/i;

/** The precache list is derived from the shell file list (single source of truth). */
export function precacheFrom(shellFiles) {
  const list = shellFiles.filter((p) => RUNTIME_FILE.test(p));
  list.forEach(assertSafePrecachePath); // an unsafe name fails the stamp, never skipped
  return list;
}

const byteCompare = (a, b) => Buffer.compare(Buffer.from(a), Buffer.from(b));

/**
 * Top-level files that are known not to be shipped. Explicit and small on purpose: any other
 * top-level file that looks like an asset makes the stamper fail instead of being ignored,
 * because an ignored shipped file would leave the cache name unchanged. Dotfiles are skipped.
 */
export const NOT_SHIPPED = new Set([
  'CLAUDE.md',
  'eslint.config.mjs',
  'package-lock.json',
  'package.json',
  'playwright.config.mjs',
]);
const SHIPPED_TOP_LEVEL = (name) =>
  name === 'index.html' || name === 'manifest.json' || /^icon-.+\.png$/.test(name);
const ASSET_LIKE =
  /\.(html?|json|webmanifest|svg|webp|ico|css|png|jpe?g|gif|avif|m?js|cjs|woff2?)$/i;

/**
 * Shell files, as POSIX paths relative to root, sorted in byte order. sw.js is handled apart.
 * Every regular file under src/ and fonts/ counts, whatever its extension; symlinks are skipped.
 * Throws if the top level holds an asset-looking file that is neither shipped nor known-unshipped.
 */
export async function listShellFiles(root) {
  const out = [];
  const unknown = [];
  for (const e of await readdir(root, { withFileTypes: true })) {
    if (!e.isFile() || e.name === 'sw.js' || e.name.startsWith('.')) continue;
    if (SHIPPED_TOP_LEVEL(e.name)) out.push(e.name);
    else if (ASSET_LIKE.test(e.name) && !NOT_SHIPPED.has(e.name)) unknown.push(e.name);
  }
  if (unknown.length > 0) {
    throw new Error(
      `unrecognised top-level file(s): ${unknown.sort(byteCompare).join(', ')}. ` +
        'They look like shipped assets but are not hashed. Move them under src/ or fonts/, ' +
        'or extend SHIPPED_TOP_LEVEL / NOT_SHIPPED in scripts/stamp-sw.mjs.',
    );
  }
  async function walk(rel) {
    let entries;
    try {
      entries = await readdir(join(root, rel), { withFileTypes: true });
    } catch {
      return; // directory does not exist yet
    }
    for (const e of entries) {
      const p = `${rel}/${e.name}`;
      if (e.isDirectory()) await walk(p);
      else if (e.isFile()) out.push(p);
    }
  }
  await walk('src');
  await walk('fonts');
  return out.sort(byteCompare);
}

/** Locate the single generated block. Throws a message naming the problem. */
function locateBlock(text) {
  const count = (needle) => text.split(needle).length - 1;
  const b = count(BEGIN);
  const e = count(END);
  if (b === 0 || e === 0)
    throw new Error(`sw.js is missing the stamp markers (${BEGIN} ... ${END})`);
  if (b > 1 || e > 1)
    throw new Error('sw.js has duplicate stamp markers; expected exactly one block');
  const start = text.indexOf(BEGIN);
  const endAt = text.indexOf(END);
  if (endAt < start) throw new Error('sw.js stamp markers are in the wrong order');
  // Block runs from the start of the begin line to the end of the end line (newline excluded).
  const from = text.lastIndexOf('\n', start) + 1;
  let to = text.indexOf('\n', endAt);
  if (to === -1) to = text.length;
  const crlf = to > 0 && text[to - 1] === '\r';
  if (crlf) to--;
  return { from, to, eol: crlf ? '\r\n' : '\n' };
}

/** sw.js text with the generated block (and its trailing newline) removed. */
export function stripBlock(text) {
  const { from, to, eol } = locateBlock(text);
  return text.slice(0, from) + text.slice(to + eol.length);
}

const SAFE_PATH = /^[A-Za-z0-9._/-]+$/;

/** Throws unless the entry is a plain same-origin relative path (no scheme, no '..', no leading '/'). */
function assertSafePrecachePath(u) {
  if (typeof u !== 'string' || !SAFE_PATH.test(u) || u.startsWith('/') || u.includes('..')) {
    throw new Error(`PRECACHE entry is not a safe relative path: ${JSON.stringify(u)}`);
  }
}

export function renderBlock(version, precache, eol = '\n') {
  if (!/^[0-9A-Za-z]{1,64}$/.test(version)) {
    throw new Error(`invalid version: ${JSON.stringify(version)}`);
  }
  precache.forEach(assertSafePrecachePath);
  const list = precache.map((u) => JSON.stringify(u)).join(', ');
  return [
    `${BEGIN}${BEGIN_NOTE}`,
    `const VERSION = '${version}';`,
    `const PRECACHE = [${list}];`,
    END,
  ].join(eol);
}

/** Replace the block in sw.js text. Returns the new text. */
export function applyBlock(text, version, precache) {
  const { from, to, eol } = locateBlock(text);
  return text.slice(0, from) + renderBlock(version, precache, eol) + text.slice(to);
}

/** The precache list for the tree under root. */
export async function listPrecache(root) {
  return precacheFrom(await listShellFiles(root));
}

/**
 * First 12 hex chars of SHA-256 over the shell files, the block-less sw.js and the rendered
 * precache list (so changing the list or its filter changes the release even if no file did).
 */
export async function computeVersion(root) {
  const swText = await readFile(join(root, 'sw.js'), 'utf8');
  const shell = await listShellFiles(root);
  const files = [];
  for (const p of shell) files.push([p, await readFile(join(root, p))]);
  files.push(['sw.js', Buffer.from(stripBlock(swText), 'utf8')]);
  // ':' cannot occur in a safe shell path, so this pseudo-entry never collides with a file.
  files.push(['stamp:precache', Buffer.from(JSON.stringify(precacheFrom(shell)), 'utf8')]);
  files.sort((a, b) => byteCompare(a[0], b[0]));
  const h = createHash('sha256');
  for (const [p, bytes] of files) {
    h.update(p);
    h.update('\0');
    h.update(String(bytes.length));
    h.update('\0');
    h.update(bytes);
  }
  return h.digest('hex').slice(0, 12);
}

/** Stamp (or check) the sw.js under root. Returns { code, message, wrote }. */
export async function run(root, { check = false } = {}) {
  const swPath = join(root, 'sw.js');
  let current;
  let next;
  try {
    current = await readFile(swPath, 'utf8');
    next = applyBlock(current, await computeVersion(root), await listPrecache(root));
  } catch (err) {
    return { code: 1, wrote: false, message: `stamp-sw: ${err.message}` };
  }
  if (next === current) return { code: 0, wrote: false, message: 'stamp-sw: sw.js is up to date' };
  if (check) {
    return {
      code: 1,
      wrote: false,
      message:
        'stamp-sw: sw.js is stale (shell files changed). Run `npm run stamp` and commit sw.js.',
    };
  }
  await writeFile(swPath, next);
  return { code: 0, wrote: true, message: 'stamp-sw: sw.js updated' };
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  const args = process.argv.slice(2);
  const check = args.includes('--check');
  const dir = args.find((a) => !a.startsWith('--'));
  const root = dir ? resolve(dir) : resolve(dirname(fileURLToPath(import.meta.url)), '..');
  const result = await run(root, { check });
  (result.code === 0 ? console.log : console.error)(result.message);
  process.exitCode = result.code;
}
