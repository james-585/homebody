// Stamps the service worker with a content hash of the app shell (ADR 0003).
//   node scripts/stamp-sw.mjs [--check] [rootDir]
// Hashes every shell file (index.html, manifest.json, icon-*.png, src/**/*.js, fonts/*.woff2) and
// sw.js itself with the generated block removed, then rewrites the marked block in sw.js.
// --check writes nothing and exits 1 if the block is stale or the markers are wrong.
import { createHash } from 'node:crypto';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const BEGIN = '// >>> stamp-sw:begin';
const END = '// <<< stamp-sw:end';
const BEGIN_NOTE = ' (generated by scripts/stamp-sw.mjs; run `npm run stamp`, do not edit)';

/** Fixed in this task (runtime behaviour unchanged); T3 widens it. */
export const PRECACHE = ['manifest.json'];

const byteCompare = (a, b) => Buffer.compare(Buffer.from(a), Buffer.from(b));

/** Shell files, as POSIX paths relative to root, sorted in byte order. sw.js is handled apart. */
export async function listShellFiles(root) {
  const out = [];
  const top = await readdir(root, { withFileTypes: true });
  for (const e of top) {
    if (!e.isFile()) continue;
    if (e.name === 'index.html' || e.name === 'manifest.json') out.push(e.name);
    else if (/^icon-.+\.png$/.test(e.name)) out.push(e.name);
  }
  async function walk(rel) {
    let entries;
    try {
      entries = await readdir(join(root, rel), { withFileTypes: true });
    } catch {
      return; // directory does not exist yet
    }
    for (const e of entries) {
      const p = `${rel}/${e.name}`;
      if (e.isDirectory()) await walk(p);
      else if (e.isFile() && e.name.endsWith('.js')) out.push(p);
    }
  }
  await walk('src');
  try {
    for (const e of await readdir(join(root, 'fonts'), { withFileTypes: true })) {
      if (e.isFile() && e.name.endsWith('.woff2')) out.push(`fonts/${e.name}`);
    }
  } catch {
    // no fonts directory yet
  }
  return out.sort(byteCompare);
}

/** Locate the single generated block. Throws a message naming the problem. */
function locateBlock(text) {
  const count = (needle) => text.split(needle).length - 1;
  const b = count(BEGIN);
  const e = count(END);
  if (b === 0 || e === 0)
    throw new Error(`sw.js is missing the stamp markers (${BEGIN} ... ${END})`);
  if (b > 1 || e > 1)
    throw new Error('sw.js has duplicate stamp markers; expected exactly one block');
  const start = text.indexOf(BEGIN);
  const endAt = text.indexOf(END);
  if (endAt < start) throw new Error('sw.js stamp markers are in the wrong order');
  // Block runs from the start of the begin line to the end of the end line (newline excluded).
  const from = text.lastIndexOf('\n', start) + 1;
  let to = text.indexOf('\n', endAt);
  if (to === -1) to = text.length;
  return { from, to };
}

/** sw.js text with the generated block (and its trailing newline) removed. */
export function stripBlock(text) {
  const { from, to } = locateBlock(text);
  return text.slice(0, from) + text.slice(Math.min(to + 1, text.length));
}

export function renderBlock(version, precache = PRECACHE) {
  const list = precache.map((u) => `'${u}'`).join(', ');
  return [
    `${BEGIN}${BEGIN_NOTE}`,
    `const VERSION = '${version}';`,
    `const PRECACHE = [${list}];`,
    END,
  ].join('\n');
}

/** Replace the block in sw.js text. Returns the new text. */
export function applyBlock(text, version) {
  const { from, to } = locateBlock(text);
  return text.slice(0, from) + renderBlock(version) + text.slice(to);
}

/** First 12 hex chars of SHA-256 over the shell files and the block-less sw.js. */
export async function computeVersion(root) {
  const swText = await readFile(join(root, 'sw.js'), 'utf8');
  const files = [];
  for (const p of await listShellFiles(root)) files.push([p, await readFile(join(root, p))]);
  files.push(['sw.js', Buffer.from(stripBlock(swText), 'utf8')]);
  files.sort((a, b) => byteCompare(a[0], b[0]));
  const h = createHash('sha256');
  for (const [p, bytes] of files) {
    h.update(p);
    h.update('\0');
    h.update(String(bytes.length));
    h.update('\0');
    h.update(bytes);
  }
  return h.digest('hex').slice(0, 12);
}

/** Stamp (or check) the sw.js under root. Returns { code, message, wrote }. */
export async function run(root, { check = false } = {}) {
  const swPath = join(root, 'sw.js');
  let current;
  let next;
  try {
    current = await readFile(swPath, 'utf8');
    next = applyBlock(current, await computeVersion(root));
  } catch (err) {
    return { code: 1, wrote: false, message: `stamp-sw: ${err.message}` };
  }
  if (next === current) return { code: 0, wrote: false, message: 'stamp-sw: sw.js is up to date' };
  if (check) {
    return {
      code: 1,
      wrote: false,
      message:
        'stamp-sw: sw.js is stale (shell files changed). Run `npm run stamp` and commit sw.js.',
    };
  }
  await writeFile(swPath, next);
  return { code: 0, wrote: true, message: 'stamp-sw: sw.js updated' };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const check = args.includes('--check');
  const dir = args.find((a) => !a.startsWith('--'));
  const root = dir ? resolve(dir) : resolve(dirname(fileURLToPath(import.meta.url)), '..');
  const result = await run(root, { check });
  (result.code === 0 ? console.log : console.error)(result.message);
  process.exitCode = result.code;
}
